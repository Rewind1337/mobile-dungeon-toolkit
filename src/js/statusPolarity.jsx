export function getStatusPolarity(status) {
    if (!status) return "special"
    if (status.id <= 16) return "buff"
    if (status.id <= 38) return "debuff"
    return (SPECIAL_STATUS_POLARITY[status.name] ?? "Special").toLowerCase()
}
